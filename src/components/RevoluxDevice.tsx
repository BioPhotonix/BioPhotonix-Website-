/** Type size in the render's pixels: the name spans about 45% of the box face. */
const WORDMARK_SIZE = 22;

/** Scale and offset that centre the name's ink on the box face. */
const wordmarkTransform = (() => {
  const [x0, y0, x1, y1] = WORDMARK.ink;
  const s = WORDMARK_SIZE / 1000;
  const tx = CONTROL_BOX.x - ((x0 + x1) / 2) * s;
  const ty = CONTROL_BOX.y - ((y0 + y1) / 2) * s;
  return `translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${s})`;
})();

