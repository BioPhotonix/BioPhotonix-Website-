"use client";

import { useId } from "react";
import Image from "next/image";

/**
 * The front render with therapy light rising from both eyepieces.
 *
 * The glow is anchored to the apertures rather than eyeballed. Their centres
 * were found by detecting the teal-rimmed openings in the render itself:
 * (89.7, 147.4) and (214.9, 147.9) in its 305 x 660 pixels, which is
 * 29.4% / 22.3% and 70.5% / 22.4%, with an aperture radius of 9.7% of the
 * width. The wrapper carries the render's own aspect ratio, so those
 * percentages land on the apertures at every size. If the render is ever
 * replaced, re-measure: nothing here infers the position from the artwork at
 * runtime.
 *
 * The light builds over five seconds and then holds, rather than pulsing,
 * because that is what a treatment session does. Under reduced motion it is
 * simply present at full strength.
 *
 * `label` prints the device's name on the black control box, so a reader can
 * tell at a glance what the device is called. It is placed the way a maker
 * would print it. The box's front face runs from x 67 to 238 and y 320 to
 * 428 of the render's pixels, and it has a faint round button centred at
 * (152, 355) with a radius of about 25px, so the name sits in the clear band
 * beneath the button, centred on the device's axis (x 152.3, the midpoint of
 * the two apertures). The first version was printed across the button, which
 * no product would do, and was a large part of why it looked stuck on.
 *
 * It is set the way device branding is: Montserrat SemiBold in spaced
 * capitals, about 47% of the face's width, in teal ink that is a shade
 * lighter at the top than the bottom, as the box's own lighting is, with
 * edges softened by a fifth of a pixel to match the render's, and a faint
 * light lip under each letter, as on a printed or inset mark. The letters are
 * outlines (scripts/wordmark-outline.py) in an SVG laid over the render in
 * its own pixels, not text: text snaps to whole pixels and slipped against
 * the floating device.
 */

/** Where the name sits: the clear band under the button, on the device's axis. */
const NAME_AT = { x: 152.3, y: 405 } as const;
/** Width of the name in the render's pixels. */
const NAME_WIDTH = 80;

/**
 * "REVOLUX" in Montserrat SemiBold (OFL) with 0.2em tracking, in a 1000-unit
 * em with the baseline at 0, and the box its ink covers. Generated by
 * scripts/wordmark-outline.py; regenerate rather than edit.
 */
const WORDMARK = {
  d: "M94 0V-700H381Q521 -700 600.5 -634Q680 -568 680 -451Q680 -374 644 -318.5Q608 -263 542 -234Q537 -231 531 -229L692 0H552L409 -205Q396 -204 382 -204H224V0ZM224 -311H376Q462 -311 505.5 -348Q549 -385 549 -451Q549 -518 505.5 -554Q462 -590 376 -590H224ZM1025 0V-700H1536V-591H1155V-409H1493V-302H1155V-109H1550V0ZM2102 0 1796 -700H1937L2170 -160L2405 -700H2535L2230 0ZM3152 10Q3070 10 3001 -17Q2932 -44 2881 -92.5Q2830 -141 2802 -206.5Q2774 -272 2774 -350Q2774 -428 2802 -493.5Q2830 -559 2881 -607.5Q2932 -656 3001 -683Q3070 -710 3151 -710Q3233 -710 3301.5 -683Q3370 -656 3421 -607.5Q3472 -559 3500 -493.5Q3528 -428 3528 -350Q3528 -272 3500 -206Q3472 -140 3421 -92Q3370 -44 3301.5 -17Q3233 10 3152 10ZM3151 -104Q3204 -104 3249 -122Q3294 -140 3327 -173.5Q3360 -207 3378.5 -251.5Q3397 -296 3397 -350Q3397 -404 3378.5 -448.5Q3360 -493 3327 -526.5Q3294 -560 3249 -578Q3204 -596 3151 -596Q3098 -596 3053.5 -578Q3009 -560 2975.5 -526.5Q2942 -493 2923.5 -448.5Q2905 -404 2905 -350Q2905 -297 2923.5 -252Q2942 -207 2975 -173.5Q3008 -140 3053 -122Q3098 -104 3151 -104ZM3866 0V-700H3996V-110H4362V0ZM4966 10Q4822 10 4740.5 -71Q4659 -152 4659 -305V-700H4789V-310Q4789 -202 4835.5 -153Q4882 -104 4967 -104Q5052 -104 5098 -153Q5144 -202 5144 -310V-700H5272V-305Q5272 -152 5190.5 -71Q5109 10 4966 10ZM5569 0 5829 -357 5583 -700H5730L5909 -451L6086 -700H6227L5982 -362L6245 0H6095L5905 -266L5717 0Z",
  ink: [94, -710, 6245, 10],
} as const;

/** Scale and offset that centre the name's ink on its place. */
const NAME = (() => {
  const [x0, y0, x1, y1] = WORDMARK.ink;
  const s = NAME_WIDTH / (x1 - x0);
  const tx = NAME_AT.x - ((x0 + x1) / 2) * s;
  const ty = NAME_AT.y - ((y0 + y1) / 2) * s;
  /** Half the cap height, for the ink's gradient. */
  const half = ((y1 - y0) * s) / 2;
  return { transform: `translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${s.toFixed(6)})`, top: NAME_AT.y - half, bottom: NAME_AT.y + half };
})();

/** Aperture centres, as a share of the render's width and height. */
const APERTURES = [
  { x: 29.42, y: 22.33 },
  { x: 70.47, y: 22.41 },
] as const;

/** Midway between the two eyepieces, as fractions of the device's box: where the hero's photons converge. */
export const EYEPIECES = {
  x: (APERTURES[0].x + APERTURES[1].x) / 200,
  y: (APERTURES[0].y + APERTURES[1].y) / 200,
} as const;

type Props = {
  alt: string;
  /** Sizes hint for the image, since this is used at two different widths. */
  sizes: string;
  priority?: boolean;
  className?: string;
  /** Name to print on the control box, if any. */
  label?: string;
};

export default function RevoluxDevice({ alt, sizes, priority = false, className = "", label }: Props) {
  /* For the gradient and filter: one per device on the page, and safe inside url(#...). */
  const id = `wm${useId().replace(/[^a-zA-Z0-9_-]/g, "")}`;
  return (
    <div className={`vt-device relative aspect-[305/660] ${className}`}>
      <Image
        src="/images/revolux-front.png"
        alt={alt}
        width={305}
        height={660}
        priority={priority}
        sizes={sizes}
        className="absolute inset-0 h-full w-full object-contain drop-shadow-[0_30px_60px_rgba(27,195,205,0.22)]"
      />

      {/* Decorative: the image's alt text already names the device. */}
      {label && (
        <svg
          aria-hidden="true"
          viewBox="0 0 305 660"
          className="pointer-events-none absolute inset-0 h-full w-full"
        >
          <defs>
            {/* Lit from above, like the box: a shade lighter at the top of the letters. */}
            <linearGradient id={`${id}-ink`} x1="0" y1={NAME.top} x2="0" y2={NAME.bottom} gradientUnits="userSpaceOnUse">
              <stop offset="0" stopColor="#46d6de" />
              <stop offset="1" stopColor="#139da6" />
            </linearGradient>
            <filter id={`${id}-soft`} x="-5%" y="-30%" width="110%" height="160%">
              <feGaussianBlur stdDeviation="0.18" />
            </filter>
          </defs>
          <g filter={`url(#${id}-soft)`}>
            {/* The lip: light catching the lower edge of each letter. */}
            <path transform={`translate(0 0.45) ${NAME.transform}`} d={WORDMARK.d} fill="#ffffff" opacity="0.1" />
            <path transform={NAME.transform} d={WORDMARK.d} fill={`url(#${id}-ink)`} />
          </g>
        </svg>
      )}

      {APERTURES.map((a) => (
        <span key={a.x} aria-hidden="true" className="pointer-events-none absolute inset-0">
          {/* Halo: the light spilling out around the eyepiece. */}
          <span
            className="device-glow absolute aspect-square w-[62%] rounded-full"
            style={{
              left: `${a.x}%`,
              top: `${a.y}%`,
              background:
                "radial-gradient(circle, rgba(255,86,56,0.62) 0%, rgba(255,72,44,0.3) 26%, rgba(255,64,40,0.12) 48%, rgba(255,60,38,0) 70%)",
            }}
          />
          {/* Source: the aperture itself, lit. */}
          <span
            className="device-glow device-glow-core absolute aspect-square w-[21%] rounded-full"
            style={{
              left: `${a.x}%`,
              top: `${a.y}%`,
              background:
                "radial-gradient(circle, rgba(255,176,150,0.92) 0%, rgba(255,104,70,0.8) 38%, rgba(255,80,50,0.34) 68%, rgba(255,74,46,0) 100%)",
            }}
          />
        </span>
      ))}
    </div>
  );
}
